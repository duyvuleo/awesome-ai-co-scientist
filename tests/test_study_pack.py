"""Local synthetic fixtures test the record contract, not any research system."""
import hashlib
import json
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
import study_pack


class StudyPackTests(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name) / "pack"

    def create(self, recipe="evaluator-integrity", resources=None):
        return study_pack.create_pack(recipe, resources or ["agentic-scientist-system"], self.root)

    def save(self, record):
        (self.root / "run-record.json").write_text(json.dumps(record), encoding="utf-8")

    def complete_fixture(self):
        """A synthetic local file exercises schema completion; no upstream code runs."""
        record = self.create()
        record["status"] = "completed"
        for key in study_pack.TEXT_FIELDS:
            record["protocol"][key] = "Synthetic schema fixture only; no research claim."
        record["protocol"].update({"baselines": ["Expected fixture text"],
                                  "controls": ["Deliberately changed fixture text"],
                                  "configuration": {"fixture": "synthetic"}, "sample_size": 1})
        record["protocol"]["budget"].update({"max_wall_seconds": 10,
                                              "max_local_compute_hours": 0.01,
                                              "max_human_hours": 0.1})
        record["execution"] = {
            "started_at": "2026-10-22T00:00:00+00:00", "ended_at": "2026-10-22T00:00:01+00:00",
            "environment": {"os": "Synthetic fixture", "runtime": "Python stdlib",
                            "hardware": "Unmeasured fixture", "dependencies": "None"},
            "commands": ["Write a synthetic text fixture; no upstream code executes."],
            "configuration": {"fixture": "synthetic"},
            "upstream_versions": [{"resource_id": "agentic-scientist-system",
                "url": "https://github.com/SakanaAI/AI-Scientist-v3", "revision_type": "git-commit",
                "revision": "0" * 40, "scope": "Synthetic schema placeholder; upstream not executed."}],
            "data_provenance": "Synthetic fixture generated by this test", "deviations": []}
        evidence = b"Synthetic fixture only. No scientific system was executed.\n"
        (self.root / "fixture.txt").write_bytes(evidence)
        record["actual"] = {
            "cost": {"paid_api_usd": 0, "wall_seconds": 1, "local_compute_hours": None,
                     "human_hours": None, "basis": "Synthetic schema values; zero API calls",
                     "excluded_costs": "Fixture values are not real execution measurements"},
            "results": [{"observation": "The synthetic file exists", "artifact_paths": ["fixture.txt"]}],
            "failures": [],
            "claim_outcomes": [{"claim": "Synthetic file exists", "outcome": "supported",
                                "scope": "File fixture only", "artifact_paths": ["fixture.txt"]}],
            "artifacts": [{"path": "fixture.txt", "sha256": hashlib.sha256(evidence).hexdigest(),
                           "description": "Synthetic test data only"}]}
        self.save(record)
        return record

    def test_each_recipe_creates_valid_unexecuted_plan(self):
        for recipe in study_pack.RECIPES:
            with self.subTest(recipe=recipe):
                path = Path(self.temporary.name) / recipe
                record = study_pack.create_pack(recipe, ["agentic-scientist-system", "paperorchestra-tool"], path)
                validated = study_pack.validate_pack(path)
                self.assertEqual(record, validated)
                self.assertIsNone(validated["execution"])
                self.assertIsNone(validated["actual"]["cost"])
                self.assertIn("not a new check", (path / "protocol.md").read_text())
                self.assertEqual({"README.md", "protocol.md", "run-record.json"}, {p.name for p in path.iterdir()})

    def test_rejects_unknown_recipe_or_resource_and_nonexecution_record(self):
        for recipe, resources in (("invented", ["agentic-scientist-system"]),
                                   ("evaluator-integrity", ["invented"]),
                                   ("evaluator-integrity", ["agentic-scientist"])):
            with self.subTest(recipe=recipe, resources=resources):
                with self.assertRaises(study_pack.InvalidPack):
                    study_pack.create_pack(recipe, resources, self.root)
                self.assertFalse(self.root.exists())

    def test_refuses_existing_output_without_touching_it(self):
        self.root.mkdir()
        sentinel = self.root / "keep.txt"
        sentinel.write_text("preserve")
        with self.assertRaises(FileExistsError):
            self.create()
        self.assertEqual("preserve", sentinel.read_text())
        self.assertEqual([sentinel], list(self.root.iterdir()))

    def test_rejects_completed_record_without_execution(self):
        record = self.create()
        record["status"] = "completed"
        self.save(record)
        with self.assertRaises(study_pack.InvalidPack):
            study_pack.validate_pack(self.root)

    def test_accepts_complete_synthetic_fixture(self):
        self.complete_fixture()
        self.assertEqual("completed", study_pack.validate_pack(self.root)["status"])

    def test_missing_revision_and_unpinned_branch_rejected(self):
        record = self.complete_fixture()
        record["execution"]["upstream_versions"] = []
        self.save(record)
        with self.assertRaisesRegex(study_pack.InvalidPack, "pinned revision"):
            study_pack.validate_pack(self.root)
        record["execution"]["upstream_versions"] = [{"resource_id": "agentic-scientist-system",
            "url": "https://github.com/SakanaAI/AI-Scientist-v3", "revision_type": "git-commit",
            "revision": "main", "scope": "Synthetic fixture"}]
        self.save(record)
        with self.assertRaisesRegex(study_pack.InvalidPack, "revision"):
            study_pack.validate_pack(self.root)

    def test_rejects_tampered_or_missing_artifact(self):
        self.complete_fixture()
        artifact = self.root / "fixture.txt"
        artifact.write_text("Changed")
        with self.assertRaisesRegex(study_pack.InvalidPack, "sha256"):
            study_pack.validate_pack(self.root)
        artifact.unlink()
        with self.assertRaisesRegex(study_pack.InvalidPack, "does not exist"):
            study_pack.validate_pack(self.root)

    def test_rejects_traversal_absolute_windows_and_symlink_paths(self):
        record = self.complete_fixture()
        artifact = record["actual"]["artifacts"][0]
        for invalid in ("../fixture.txt", str(self.root / "fixture.txt"), "C:\\fixture.txt", "sub/../fixture.txt", "./fixture.txt"):
            with self.subTest(path=invalid):
                artifact["path"] = invalid
                self.save(record)
                with self.assertRaises(study_pack.InvalidPack):
                    study_pack.validate_pack(self.root)
        (self.root / "link.txt").symlink_to(self.root / "fixture.txt")
        artifact["path"] = "link.txt"
        self.save(record)
        with self.assertRaisesRegex(study_pack.InvalidPack, "symlinks"):
            study_pack.validate_pack(self.root)

    def test_requires_evidence_references_for_observed_claim(self):
        record = self.complete_fixture()
        record["actual"]["claim_outcomes"][0]["artifact_paths"] = ["unrecorded.txt"]
        self.save(record)
        with self.assertRaisesRegex(study_pack.InvalidPack, "evidence artifact"):
            study_pack.validate_pack(self.root)

    def test_budget_overrun_requires_a_recorded_deviation(self):
        record = self.complete_fixture()
        record["actual"]["cost"]["wall_seconds"] = 11
        self.save(record)
        with self.assertRaisesRegex(study_pack.InvalidPack, "budget overruns"):
            study_pack.validate_pack(self.root)
        record["execution"]["deviations"] = ["Synthetic example: one second beyond the planned limit."]
        self.save(record)
        study_pack.validate_pack(self.root)

    def test_duplicate_json_fields_are_rejected(self):
        self.create()
        path = self.root / "run-record.json"
        path.write_text(path.read_text().replace('"schema_version": 1', '"schema_version": 1, "schema_version": 1'))
        with self.assertRaisesRegex(study_pack.InvalidPack, "duplicate JSON"):
            study_pack.validate_pack(self.root)

    def test_planned_observations_cannot_impersonate_executed_results(self):
        record = self.create()
        record["actual"]["cost"] = {"paid_api_usd": 0}
        self.save(record)
        with self.assertRaisesRegex(study_pack.InvalidPack, "unobserved"):
            study_pack.validate_pack(self.root)

    def test_requires_declared_api_budget_and_rejects_nonfinite_json(self):
        record = self.complete_fixture()
        record["actual"]["cost"]["paid_api_usd"] = 0.01
        self.save(record)
        with self.assertRaisesRegex(study_pack.InvalidPack, "budget overruns"):
            study_pack.validate_pack(self.root)
        record["protocol"]["budget"]["paid_api_usd"] = 0.02
        self.save(record)
        study_pack.validate_pack(self.root)
        record["actual"]["cost"]["paid_api_usd"] = float("nan")
        self.save(record)
        with self.assertRaisesRegex(study_pack.InvalidPack, "NaN"):
            study_pack.validate_pack(self.root)

    def test_all_current_systems_and_tools_create_valid_packs(self):
        for resource in study_pack.load():
            if resource["kind"] not in {"system", "tool"}:
                continue
            with self.subTest(resource=resource["id"]):
                path = Path(self.temporary.name) / resource["id"]
                study_pack.create_pack("evaluator-integrity", [resource["id"]], path)
                record = study_pack.validate_pack(path)
                self.assertEqual(resource["sources"], record["resources"][0]["sources"])
                self.assertEqual(0, record["protocol"]["budget"]["paid_api_usd"])

    def test_cli_alias_and_validation(self):
        script = str(ROOT / "scripts" / "study_pack.py")
        created = subprocess.run([sys.executable, script, "create", "--recipe", "evaluator-integrity",
                                  "--systems", "paperorchestra-tool", "--output", str(self.root)],
                                 capture_output=True, text=True, check=True)
        self.assertIn("No experiment was executed", created.stdout)
        checked = subprocess.run([sys.executable, script, "validate", str(self.root)],
                                 capture_output=True, text=True, check=True)
        self.assertIn("Valid planned", checked.stdout)


if __name__ == "__main__":
    unittest.main()
